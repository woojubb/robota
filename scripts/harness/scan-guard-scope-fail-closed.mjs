/** Scan scripts registered in `run-all-scans.mjs`, as bare filenames. Parsed, never hand-listed. */
export function registeredScanFiles(root = WORKSPACE_ROOT) {
  // Comments are stripped first (HARNESS-052): the raw text of the registration file names scans in
  // its own docstrings and in `// …` notes beside table entries, so a scan that had been COMMENTED
  // OUT of the table — or deleted from it and merely mentioned — still counted as registered. That
  // is the presence-of-a-string shape this item's second axis is about, in this scan's own
  // derivation. Structure lives in the array; comments are prose.
  const source = stripJsComments(readFileSync(path.join(root, REGISTRATION_FILE), 'utf8'));
  const files = [...source.matchAll(/scripts\/harness\/([a-z0-9-]+\.mjs)/g)].map((m) => m[1]);
  if (files.length === 0)
    throw new Error(
      `${REGISTRATION_FILE} parsed to zero registered scans. An empty registration list would ` +
        "satisfy every assertion below vacuously — which is this scan's own defect.",
    );
  return [...new Set(files)].sort();
}

/**
 * Exported finders of one harness script that take a `root`. The shape that makes a guard checkable
 * here.
 *
 * THIS REGEX IS THE WHOLE RULE, so its narrowness is the whole hole. It first read
 * `export function (find…)\(\s*root\s*=`, which matched neither `export async function` nor a
 * `collect…` finder nor a `root` parameter without a default. Measured: 20 of 41 finders derived,
 * and this scan did not classify ITSELF — `findGuardScopeFindings` is `async`. Falsified by
 * registering a scan exporting `export async function findBogusFindings(root = X) { return []; }`,
 * unconditionally vacuous for every root: the completeness rule passed. Changing the single keyword
 * `async function` → `function` made the same file fail. A rule whose verdict turns on a keyword is
 * measuring spelling, not structure — which is this scan's own subject, one level up.
 */
export function rootFinderExports(sourceText) {
  return [
    ...stripJsComments(String(sourceText ?? '')).matchAll(
      /export\s+(?:async\s+)?function\s+((?:find|collect)[A-Za-z0-9_]*)\(\s*root\b/g,
    ),
  ]
    .map((match) => match[1])
    .sort();
}

/**
 * Remove block and line comments before matching declarations.
 *
 * Not cosmetic. Without it this scan matched the `export async function findBogusFindings(root = X)`
 * written in its OWN docstring above and derived a finder for a function that does not exist — a
 * scan reading its own documentation as evidence, which is the failure mode `scan-orchestration-map`
 * and `check-test-coverage-scripts` were separately found to have. A declaration is code, so only
 * code is searched.
 */
export function stripJsComments(sourceText) {
  return String(sourceText ?? '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}

/** Every `{ file, finder }` pair this scan is responsible for classifying, derived from the tree. */
export function derivedFinders(root = WORKSPACE_ROOT) {
  const pairs = [];
  for (const file of registeredScanFiles(root)) {
    const source = readFileSync(path.join(root, HARNESS_DIR, file), 'utf8');
    for (const finder of rootFinderExports(source)) pairs.push({ file, finder });
  }
  return pairs;
}

const keyOf = (entry) => `${entry.file}#${entry.finder}`;

/** Rule 1: every derived finder classified exactly once, and no table entry left behind. */
export function classificationFindings(root = WORKSPACE_ROOT) {
  const findings = [];
  const derived = new Set(derivedFinders(root).map(keyOf));
  const mandatory = MANDATORY_TREE_GUARDS.map(keyOf);
  const pending = PENDING_CLASSIFICATION.map(keyOf);
  const declared = new Set([...mandatory, ...pending]);

  for (const key of [...derived].sort()) {
    if (!declared.has(key))
      findings.push({
        subject: key,
        detail:
          'is a registered scan exporting a root finder, and is in neither MANDATORY_TREE_GUARDS ' +
          'nor PENDING_CLASSIFICATION. Classify it: run it against a root without its governed ' +
          'tree and record whether it fails closed.',
      });
  }
  for (const key of [...declared].sort()) {
    if (!derived.has(key))
      findings.push({
        subject: key,
        detail:
          'is declared here but is no longer a registered scan exporting that finder. A stale ' +
          'declaration is a rule that guards nothing — remove it or fix the name.',
      });
  }
  const both = mandatory.filter((key) => pending.includes(key));
  for (const key of both)
    findings.push({
      subject: key,
      detail: 'appears in BOTH tables — it must appear in exactly one.',
    });

  // EXACTLY ONE means exactly one, including within a single table. The cross-table rule above was
  // the whole of it, so `scan-test-selection-tolerance#findTestSelectionFindings` sat in
  // PENDING_CLASSIFICATION TWICE — measured twice, counted twice in the summary line, and a future
  // repair would have had to be noticed twice. A rule stated as "exactly one" that only checks
  // "not two tables" is the audited shape in miniature.
  for (const [table, keys] of [
    ['MANDATORY_TREE_GUARDS', mandatory],
    ['PENDING_CLASSIFICATION', pending],
  ]) {
    const counts = new Map();
    for (const key of keys) counts.set(key, (counts.get(key) ?? 0) + 1);
    for (const [key, count] of counts) {
      if (count > 1)
        findings.push({
          subject: key,
          detail: `appears ${count} times in ${table} — it must appear exactly once.`,
        });
    }
  }
  return findings;
}

/** Rule 2: run one mandatory guard against a root lacking its governed tree. */
async function behaviourFinding(entry, root) {
  const module = await import(pathToFileURL(path.join(root, HARNESS_DIR, entry.file)).href);
  const finder = module[entry.finder];
  if (typeof finder !== 'function')
    return {
      subject: keyOf(entry),
      detail: `does not export \`${entry.finder}\` as a function — the declaration is stale.`,
    };

  const bare = mkdtempSync(path.join(tmpdir(), 'guard-scope-'));
  try {
    let result;
    try {
      // AWAITED (HARNESS-052): without this an async finder resolves to a Promise, which is neither
      // an array nor `{findings}`, so it would be reported as a violation no matter how it behaves.
      // That defect and the sync-only derivation regex above masked each other exactly.
      result = await finder(bare);
    } catch {
      return undefined; // threw on an unreadable root — fail-closed, which is the requirement
    }
    const list = Array.isArray(result) ? result : (result?.findings ?? null);
    const otherSignals =
      result && !Array.isArray(result)
        ? Object.entries(result).some(
            ([key, value]) => key !== 'findings' && Array.isArray(value) && value.length > 0,
          )
        : false;
    if ((list?.length ?? 0) > 0 || otherSignals) return undefined; // reported something — fail-closed
    return {
      subject: keyOf(entry),
      detail:
        `returned an EMPTY finding list for a root with no \`${entry.tree}\`. ${entry.why}. ` +
        'Make the missing tree an error, not a pass.',
    };
  } finally {
    rmSync(bare, { recursive: true, force: true });
  }
}

/**
 * How long one ledger measurement may take before it is treated as unmeasurable.
 *
 * Importing an arbitrary harness module executes its top-level code, and some of the 44 modules do
 * real work there. One left a promise that never settled, which killed the whole scan with node's
 * `ERR_UNSETTLED_TOPLEVEL_AWAIT` (exit 13) and NO output — a guard dying silently mid-run while
 * measuring other guards for dying silently. Bounded and caught, an unmeasurable entry becomes a
 * finding instead.
 */
const MEASURE_TIMEOUT_MS = 15_000;

/**
 * The verdict a finder actually produces when handed a root without its governed tree.
 *
 * EXPORTED so the ledger is regenerated by the exact code path that later verifies it. The first
 * ledger was generated by a throwaway `node -e` loop whose catch scored ANY failure as
 * `fail-closed` — and several harness modules call `pathToFileURL(process.argv[1])` at import time,
 * which throws under `node -e` where `argv[1]` is undefined. Those entries recorded an import crash
 * as correct behaviour. Two measurement paths that disagree is one measurement path too many.
 */
export async function measureFinder(entry, root = WORKSPACE_ROOT) {
  const bare = mkdtempSync(path.join(tmpdir(), 'guard-scope-measure-'));
  let timer;
  try {
    const measure = (async () => {
      const module = await import(pathToFileURL(path.join(root, HARNESS_DIR, entry.file)).href);
      const finder = module[entry.finder];
      if (typeof finder !== 'function') return 'missing';
      let result;
      try {
        result = await finder(bare);
      } catch {
        return 'fail-closed';
      }
      const list = Array.isArray(result) ? result : (result?.findings ?? null);
      const otherSignals =
        result && !Array.isArray(result)
          ? Object.entries(result).some(
              ([key, value]) => key !== 'findings' && Array.isArray(value) && value.length > 0,
            )
          : false;
      return (list?.length ?? 0) > 0 || otherSignals ? 'fail-closed' : 'vacuous';
    })();
    const deadline = new Promise((resolve) => {
      timer = setTimeout(() => resolve('unmeasurable'), MEASURE_TIMEOUT_MS);
    });
    // An import that throws is `unmeasurable`, NOT `fail-closed`: a module that cannot even be
    // loaded has told us nothing about how its finder behaves, and scoring that as correct would be
    // this scan certifying a guard it never ran.
    return await Promise.race([measure, deadline]).catch(() => 'unmeasurable');
  } finally {
    clearTimeout(timer);
    rmSync(bare, { recursive: true, force: true });
  }
}

/**
 * Rule 3: every ledger entry's recorded `measured` value must still be the value the finder
 * produces.
 *
 * Added after this scan's ledger went stale within an hour of being written — repairing
 * `scan-conflict-markers` turned it fail-closed while the ledger still recorded it `vacuous`. A
 * debt ledger nobody re-measures becomes a set of claims about the past presented as facts about the
 * present, which is the audited defect in documentation form. The recorded verdicts are now
 * RE-EXECUTED on every run rather than trusted, so an entry cannot silently drift in either
 * direction: a scan that got fixed must be moved out, and one that regressed must be caught.
 */
export async function ledgerDriftFindings(root = WORKSPACE_ROOT) {
  const findings = [];
  for (const entry of PENDING_CLASSIFICATION) {
    // This scan's own finder cannot be measured this way: measuring it runs this loop, which
    // measures it again. It stays CLASSIFIED (rule 1 still requires that, and it is what caught the
    // async blind spot) but is exempt from rule 3, with the reason stated rather than skipped.
    if (entry.selfReferential) continue;
    const actual = await measureFinder(entry, root);
    if (actual === entry.measured) continue;
    findings.push({
      subject: keyOf(entry),
      detail:
        actual === 'missing'
          ? `is recorded here but no longer exports \`${entry.finder}\`.`
          : actual === 'unmeasurable'
            ? 'could not be measured — importing it threw, or it did not settle within ' +
              `${MEASURE_TIMEOUT_MS}ms. That is not a pass: nothing was learned about how it behaves.`
            : `is recorded as \`${entry.measured}\` but now measures \`${actual}\`. ` +
              (actual === 'fail-closed'
                ? 'It was repaired — move it to MANDATORY_TREE_GUARDS with its governed tree named, ' +
                  'so the fix is pinned rather than merely noted.'
                : 'It regressed — a guard that used to fail closed now reports a pass over a tree ' +
                  'it never read.'),
    });
  }
  return findings;
}

/** Findings across all three rules. */
/**
 * Rule 4: THE DEBT MAY SHRINK AND NEVER GROW. HARNESS-064.
 *
 * Rules 1–3 make every finder answer for itself and keep the ledger honest, but they place no bound
 * on its SIZE: a new scan could be classified `pending` forever, and a new `vacuous` entry — a live
 * instance of the audited defect — could be added with a paragraph explaining it and nothing would
 * object. The ledger was already a set of claims nobody re-measured before rule 3; without this it
 * is a set of measurements nobody bounds.
 *
 * Two ceilings, because they mean different things. `vacuous` entries are live defects and their
 * count is the one that matters most. `fail-closed` entries behave correctly but are not pinned, so
 * they are debt of a milder kind. Both are frozen; both may fall.
 *
 * Lowering either means re-freezing in the SAME change, exactly like `file-size` and
 * `spec-public-surface` — an unlocked gain is a licence to grow back.
 */
export function ledgerCeilingFindings(ceilings = loadLedgerCeilings()) {
  const vacuous = measuredVacuous().length;
  const unpinned = PENDING_CLASSIFICATION.length - vacuous;
  const findings = [];
  const check = (label, actual, frozen) => {
    if (frozen === undefined) {
      findings.push({
        subject: `ledger-ceiling:${label}`,
        detail: `${actual} entr(y/ies) with no frozen ceiling — run --write-ledger-ceilings.`,
      });
      return;
    }
    if (actual > frozen) {
      findings.push({
        subject: `ledger-ceiling:${label}`,
        detail:
          `${actual} entr(y/ies), up from a frozen ${frozen}. ` +
          (label === 'vacuous'
            ? 'A new vacuous entry is a NEW live instance of the defect this scan audits — fix the guard, do not record it.'
            : 'Pin the guard in MANDATORY_TREE_GUARDS instead of adding to the ledger.'),
      });
      return;
    }
    if (actual < frozen) {
      findings.push({
        subject: `ledger-ceiling:${label}`,
        detail:
          `${actual} entr(y/ies), DOWN from a frozen ${frozen}. Re-freeze it in this same change ` +
          '(`--write-ledger-ceilings`) — an unlocked gain is a licence to grow back.',
      });
    }
  };
  check('vacuous', vacuous, ceilings.vacuous);
  check('unpinned', unpinned, ceilings.unpinned);
  return findings;
}

/**
 * Where the frozen ceilings live — overridable, like every other path in this file.
 *
 * `GUARD_LEDGER_CEILINGS` exists for the reachability case, which has to prove the ceiling check
 * runs through the CLI and not merely as an exported helper. Its first version mutated the real
 * checked-in file and restored it in a `finally`; a kill in between — and this file's own docstring
 * records a harness scan dying mid-run with no output — would leave the working tree holding a
 * corrupted ceiling, which is the one direction this ratchet must never fail in. Everything else
 * here takes a `root` for exactly that reason.
 */
function ledgerCeilingsPath() {
  return (
    process.env['GUARD_LEDGER_CEILINGS'] ??
    path.join(WORKSPACE_ROOT, 'scripts/harness/guard-ledger-ceilings.json')
  );
}

function loadLedgerCeilings() {
  const file = ledgerCeilingsPath();
  if (!existsSync(file)) return {};
  return JSON.parse(readFileSync(file, 'utf8'));
}

export async function findGuardScopeFindings(root = WORKSPACE_ROOT) {
  const findings = classificationFindings(root);
  for (const entry of MANDATORY_TREE_GUARDS) {
    const finding = await behaviourFinding(entry, root);
    if (finding) findings.push(finding);
  }
  findings.push(...(await ledgerDriftFindings(root)));
  // Only meaningful about the real tree — a temporary root has the same ledger, but the caller that
  // hands one in is asking about tree-scope behaviour, not about this repo's debt.
  if (root === WORKSPACE_ROOT) findings.push(...ledgerCeilingFindings());
  return findings;
}

