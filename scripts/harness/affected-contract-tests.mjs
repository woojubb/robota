import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';

import {
  CONTRACT_CONTROL_PLANE_INPUTS,
  createContractTestRegistry,
  validateContractTestRegistry,
} from './contract-test-inputs.mjs';
import {
  groupContractTestsByOwner,
  ownerForRepositoryInput,
  selectionScopesForChangedPath,
} from './contract-test-owners.mjs';

const PRODUCT_SOURCE_PREFIXES = ['apps/', 'examples/', 'packages/'];
const SAFE_DEFAULT_WEIGHT = 10;

const normalize = (value) =>
  String(value ?? '')
    .trim()
    .replaceAll('\\', '/')
    .replace(/^\.\//u, '');

function defaultRunGit(args, { cwd } = {}) {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8' });
  return {
    status: result.status ?? 1,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
    signal: result.signal ?? null,
  };
}

/** Parse `git diff --name-status -z`, retaining both sides of renames and copies. */
export function parseNameStatusDiff(output) {
  const tokens = String(output ?? '').split('\0');
  if (tokens.at(-1) === '') tokens.pop();
  const files = [];
  for (let index = 0; index < tokens.length;) {
    const status = tokens[index++];
    if (!/^[ACDMRTUXB][0-9]*$/u.test(status ?? '')) {
      throw new Error(`unreadable git diff status: ${status || '<empty>'}`);
    }
    const count = /^[RC]/u.test(status) ? 2 : 1;
    for (let offset = 0; offset < count; offset += 1) {
      const file = normalize(tokens[index++]);
      if (!file) throw new Error(`unreadable git diff path after ${status}`);
      files.push(file);
    }
  }
  return [...new Set(files)].sort();
}

/** Resolve a fail-closed changed-file set from every merge base. */
export function resolveChangedContractInputs({
  root,
  baseRef,
  headRef = 'HEAD',
  runGit = defaultRunGit,
}) {
  if (!baseRef || !headRef) return { ok: false, files: [], reason: 'base/head ref is missing' };
  const merge = runGit(['merge-base', '--all', baseRef, headRef], { cwd: root });
  if (merge?.status !== 0 || merge.signal) {
    return { ok: false, files: [], reason: 'merge-base lookup failed' };
  }
  const bases = String(merge.stdout ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
  if (bases.length === 0) return { ok: false, files: [], reason: 'merge-base lookup was empty' };
  const files = new Set();
  try {
    for (const base of bases) {
      const diff = runGit(['diff', '--name-status', '-z', '-M', base, headRef], { cwd: root });
      if (diff?.status !== 0 || diff.signal) {
        return { ok: false, files: [], reason: `diff against ${base} failed` };
      }
      for (const file of parseNameStatusDiff(diff.stdout)) files.add(file);
    }
  } catch (error) {
    return { ok: false, files: [], reason: error.message };
  }
  if (files.size === 0) return { ok: false, files: [], reason: 'changed-file diff was empty' };
  return { ok: true, bases, files: [...files].sort() };
}

function globPattern(pattern) {
  let expression = '^';
  for (let index = 0; index < pattern.length; index += 1) {
    const character = pattern[index];
    if (character === '*') {
      if (pattern[index + 1] === '*') {
        index += 1;
        if (pattern[index + 1] === '/') {
          index += 1;
          expression += '(?:.*/)?';
        } else expression += '.*';
      } else expression += '[^/]*';
    } else if (character === '?') expression += '[^/]';
    else expression += character.replace(/[|\\{}()[\]^$+?.]/gu, '\\$&');
  }
  return new RegExp(`${expression}$`, 'u');
}

export function matchesInput(file, input) {
  const normalizedFile = normalize(file);
  const normalizedInput = normalize(input);
  if (!normalizedInput.includes('*') && !normalizedInput.includes('?')) {
    return normalizedFile === normalizedInput;
  }
  return globPattern(normalizedInput).test(normalizedFile);
}

const BROAD_DOMAIN_INPUTS = new Map([
  ['apps/**', 'apps'],
  ['examples/**', 'examples'],
  ['packages/**', 'packages'],
]);
const STRUCTURAL_FILE = /(?:^|\/)(?:package\.json|tsconfig(?:\.[^/]+)?\.json)$/u;

/** Broad autogenerated domain globs cover manifests by default, never every source file. */
export function matchesContractRepositoryInput(entry, file, input) {
  const domain = BROAD_DOMAIN_INPUTS.get(normalize(input));
  if (!domain) return matchesInput(file, input);
  if (!matchesInput(file, input)) return false;
  return (
    STRUCTURAL_FILE.test(normalize(file)) || entry.broadSourceDomains?.includes(domain) === true
  );
}

const isProductSource = (file) => PRODUCT_SOURCE_PREFIXES.some((prefix) => file.startsWith(prefix));
const isControlPlane = (file) =>
  CONTRACT_CONTROL_PLANE_INPUTS.some((input) => matchesInput(file, input));

function completeFallback({
  root,
  contractTests,
  isolatedContract,
  reason,
  registry,
  measuredDurations,
}) {
  const isolated = new Set(isolatedContract);
  const ordinary = contractTests.filter((file) => !isolated.has(file));
  const weights = estimateContractTestWeights({
    root,
    files: ordinary,
    registry,
    measuredDurations,
  });
  const selected = [...contractTests].sort();
  let ownerGroups;
  try {
    ownerGroups = groupContractTestsByOwner(Array.isArray(registry) ? registry : [], selected);
    if (ownerGroups.length === 0) throw new Error('owner groups are empty');
  } catch {
    ownerGroups = [Object.freeze({ owner: 'harness', tests: Object.freeze([...selected]) })];
  }
  return {
    mode: 'complete',
    reason,
    selected,
    shards: createDeterministicShards(ordinary, 4, weights),
    isolated: contractTests.filter((file) => isolated.has(file)).sort(),
    ownerGroups,
    selectedByOwner: ownerGroups,
  };
}

const positiveWeight = (value, fallback = SAFE_DEFAULT_WEIGHT) =>
  Number.isFinite(value) && value > 0 ? value : fallback;

function suppliedWeight(weights, file) {
  if (weights instanceof Map) return weights.get(file);
  if (weights && typeof weights === 'object') return weights[file];
  return undefined;
}

function occurrences(source, expression) {
  return [...source.matchAll(expression)].length;
}

/**
 * Estimate first-run milliseconds from the complete static source closure. Measured durations take
 * precedence when available; missing or invalid data degrades to a conservative positive weight.
 */
export function estimateContractTestWeights({ root, files, registry = [], measuredDurations }) {
  const entries = new Map(
    (Array.isArray(registry) ? registry : []).map((entry) => [normalize(entry?.test), entry]),
  );
  return new Map(
    files.map((file) => {
      const measured = suppliedWeight(measuredDurations, file);
      if (Number.isFinite(measured) && measured > 0) return [file, measured];

      try {
        const closure = entries.get(file)?.implementationInputs ?? [file];
        const sources = [...new Set(closure)].map((input) =>
          readFileSync(path.join(root, input), 'utf8'),
        );
        const source = sources.join('\n');
        const bytes = Buffer.byteLength(source);
        const subprocesses = occurrences(
          source,
          /\b(?:spawn|spawnSync|execFile|execFileSync|exec|execSync|fork)\s*\(/gu,
        );
        const gitRepositories = occurrences(
          source,
          /(?:['"`]git['"`]|\bgit\b)[\s\S]{0,120}?\b(?:init|clone|worktree)\b/gu,
        );
        const fanOut = occurrences(source, /\bPromise\.(?:all|allSettled)\s*\(/gu);
        const estimate =
          SAFE_DEFAULT_WEIGHT +
          Math.ceil(bytes / 2_048) +
          sources.length * 2 +
          subprocesses * 100 +
          gitRepositories * 250 +
          fanOut * 150;
        return [file, positiveWeight(estimate)];
      } catch {
        return [file, SAFE_DEFAULT_WEIGHT];
      }
    }),
  );
}

/** Deterministic LPT partition. Every file appears exactly once. */
export function createDeterministicShards(files, count = 4, weights = new Map()) {
  if (!Number.isSafeInteger(count) || count < 1) throw new Error('shard count must be positive');
  const unique = [...new Set(files)].sort();
  if (unique.length !== files.length) throw new Error('cannot shard duplicate test files');
  const shards = Array.from({ length: count }, (_, index) => ({ index, load: 0, files: [] }));
  const jobs = unique
    .map((file) => ({ file, weight: positiveWeight(suppliedWeight(weights, file)) }))
    .sort((left, right) => right.weight - left.weight || left.file.localeCompare(right.file));
  for (const job of jobs) {
    const target = shards.reduce((lightest, shard) =>
      shard.load < lightest.load || (shard.load === lightest.load && shard.index < lightest.index)
        ? shard
        : lightest,
    );
    target.files.push(job.file);
    target.load += job.weight;
  }
  return shards.map((shard) => shard.files.sort());
}

/**
 * Build an affected or complete execution plan. Any ambiguity expands coverage; only recognized
 * product source is allowed to settle on the safety floor without a repository-input match.
 */
export function createAffectedContractPlan({
  root,
  contractTests,
  isolatedContract = [],
  changedFiles,
  registry,
  measuredDurations,
}) {
  const contracts = [...contractTests].map(normalize).sort();
  let entries;
  try {
    entries = registry ?? createContractTestRegistry(root, contracts);
    validateContractTestRegistry(root, contracts, entries);
  } catch (error) {
    return completeFallback({
      root,
      contractTests: contracts,
      isolatedContract,
      reason: `invalid registry: ${error.message}`,
      registry: entries ?? registry,
      measuredDurations,
    });
  }
  const changed = [...new Set((changedFiles ?? []).map(normalize).filter(Boolean))].sort();
  if (changed.length === 0) {
    return completeFallback({
      root,
      contractTests: contracts,
      isolatedContract,
      reason: 'changed-file input was missing or empty',
      registry: entries,
      measuredDurations,
    });
  }
  if (changed.some((file) => file.startsWith('../') || path.isAbsolute(file))) {
    return completeFallback({
      root,
      contractTests: contracts,
      isolatedContract,
      reason: 'changed-file input escaped the repository',
      registry: entries,
      measuredDurations,
    });
  }
  const byTest = new Map(entries.map((entry) => [entry.test, entry]));
  const selected = new Set(entries.filter((entry) => entry.always).map((entry) => entry.test));
  const recognized = new Set();

  for (const file of changed) {
    if (isControlPlane(file)) {
      return completeFallback({
        root,
        contractTests: contracts,
        isolatedContract,
        reason: `control-plane input changed: ${file}`,
        registry: entries,
        measuredDurations,
      });
    }
    if (byTest.has(file)) {
      selected.add(file);
      recognized.add(file);
    }
    const changedScopes = selectionScopesForChangedPath(root, file);
    if (!changedScopes) {
      return completeFallback({
        root,
        contractTests: contracts,
        isolatedContract,
        reason: `unknown owner for changed input: ${file}`,
        registry: entries,
        measuredDurations,
      });
    }
    recognized.add(file);
    const changedPrimaryOwner = ownerForRepositoryInput(root, file);
    let dependencyMatched = byTest.has(file);
    for (const entry of entries) {
      const implementationMatch = entry.implementationInputs.includes(file);
      const sameSpecificOwner =
        /^(?:package|app|example):/u.test(entry.primaryOwner) &&
        entry.primaryOwner === changedPrimaryOwner;
      const globalInputMatch =
        (entry.primaryOwner === 'harness' || entry.primaryOwner.startsWith('workspace:')) &&
        entry.repositoryInputs.some((input) => matchesContractRepositoryInput(entry, file, input));
      if (implementationMatch || sameSpecificOwner || globalInputMatch) {
        selected.add(entry.test);
        recognized.add(file);
        dependencyMatched = true;
      }
    }
    if (changedPrimaryOwner === 'harness' && !dependencyMatched) {
      return completeFallback({
        root,
        contractTests: contracts,
        isolatedContract,
        reason: `unmatched harness implementation changed: ${file}`,
        registry: entries,
        measuredDurations,
      });
    }
    if (isProductSource(file)) recognized.add(file);
  }

  const unknown = changed.filter((file) => !recognized.has(file));
  if (unknown.length > 0) {
    return completeFallback({
      root,
      contractTests: contracts,
      isolatedContract,
      reason: `unknown input changed: ${unknown[0]}`,
      registry: entries,
      measuredDurations,
    });
  }
  if (selected.size === 0) {
    return completeFallback({
      root,
      contractTests: contracts,
      isolatedContract,
      reason: 'affected selection contained zero tests',
      registry: entries,
      measuredDurations,
    });
  }
  const isolated = new Set(isolatedContract);
  const selectedFiles = [...selected].sort();
  const ownerGroups = groupContractTestsByOwner(entries);
  return {
    mode: 'affected',
    reason: `${selectedFiles.length} of ${contracts.length} contract tests selected`,
    selected: selectedFiles,
    shards: [selectedFiles.filter((file) => !isolated.has(file))],
    isolated: selectedFiles.filter((file) => isolated.has(file)),
    ownerGroups,
    selectedByOwner: groupContractTestsByOwner(entries, selectedFiles),
  };
}
