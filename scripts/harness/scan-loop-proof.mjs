#!/usr/bin/env node

/**
 * HARNESS-113 — a new scan must prove itself; a new orchestration must too.
 *
 * `learning-loop.md` already places a proof obligation on one harness artifact class:
 *
 * > **Prove the check.** A new check must demonstrably FAIL on the triggering incident (or a fixture
 * > that reproduces it) and PASS after the fix; a check that would not have caught the original event
 * > is not enforcement.
 *
 * A SKILL had no counterpart. Measured when this file was written, grepping the rules and skills trees
 * for a prove-before-automate requirement returned nothing, while sixteen of fifty-eight skills drove a
 * loop. Nothing required any of them to have been executed end to end before it was authored,
 * registered, routed and made dispatchable.
 *
 * The asymmetry runs the wrong way. A wrong scan exits 1 locally and someone reads the message. A wrong
 * orchestration fails by DISPATCHING — it spends a fan-out before anyone learns the routing was wrong.
 * The artifact whose failure is more expensive carried the weaker admission gate.
 *
 * ## What counts as proof, and why it is an artifact rather than an assertion
 *
 * A CLOSED entry in the skill's `.agents/loop-runs/` ledger (HARNESS-112). The shape is CNCF's
 * Kubernetes conformance programme's: a distribution is not certified by asserting that it conforms —
 * the vendor submits `e2e.log` and `junit_01.xml`, the output files of an actual run, in the same pull
 * request as the claim. Proof generated by the thing being proven is the grading-own-homework shape
 * this repository refuses everywhere else.
 *
 * ## Three ways to satisfy it
 *
 *   1. a closed ledger entry — the skill has been driven to a terminal signal at least once;
 *   2. `proof: none — <reason>` in the skill's frontmatter, mirroring `Enforced by: nothing — <why>`.
 *      Both are answers; silence is what a reader cannot tell from proof. The reason must BE a reason,
 *      anchored the same way `scan-rule-case-narrative`'s `allow-citation` is;
 *   3. membership of the frozen baseline — the skills that predate this floor.
 *
 * The baseline is a SET and not a count, for the reason `scan-spec-user-execution-section` records: a
 * count lets a new skill borrow an old one's exemption, and all of the value is in new work. It may
 * only SHRINK — a baseline entry that now has a closed run is a finding, so the exemption cannot
 * outlive the need for it.
 *
 * ## The ceiling, stated rather than implied
 *
 * This cannot see whether the recorded run exercised the loop's hard path. It establishes that a
 * terminal signal was reached once. That is strictly more than the zero it replaces, and it is not
 * more than that.
 *
 * fail-direction: refuse — an unreadable ledger is a finding, never "no runs yet".
 *
 * Usage: `node scripts/harness/scan-loop-proof.mjs`
 * Exit 0 = every loop-driving skill is proven, exempted with a reason, or frozen; 1 = findings.
 */

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

import { requireGovernedTree } from './governed-tree.mjs';
import { frontmatterObject } from './frontmatter.mjs';
import { readLedger } from './loop-run.mjs';
import { parseDeclaration } from './scan-loop-contract.mjs';
import { resolveWorkspaceRoot } from './shared.mjs';

const WORKSPACE_ROOT = resolveWorkspaceRoot(import.meta);
const SKILLS_DIR = '.agents/skills';
export const BASELINE_FILE = path.join(WORKSPACE_ROOT, 'scripts/harness/loop-proof-baseline.json');

/**
 * The exemption form. Anchored on a non-empty reason after the dash, because `proof: none —` satisfies
 * "some text is present" and an exception nobody had to justify is the one that spreads.
 */
const EXEMPTION = /^none\s*[—-]\s*(\S[^\n]*)$/;

let examinedSkills = 0;

/** How many loop-driving skills the last sweep JUDGED. */
export function examinedSkillCount() {
  return examinedSkills;
}

function readBaseline(file = BASELINE_FILE) {
  if (!existsSync(file)) return [];
  return JSON.parse(readFileSync(file, 'utf8')).exempt ?? [];
}

/**
 * Findings over every loop-driving skill.
 *
 * @param {string} root
 * @param {string[]} [baseline] the frozen exempt SET; injected so a case can pin it.
 */
export function findLoopProofFindings(root = WORKSPACE_ROOT, baseline = undefined) {
  requireGovernedTree(root, SKILLS_DIR, {
    scan: 'loop-proof',
    why: 'The skills tree IS the population this floor governs; over a root without it there is no skill to prove and "no findings" would mean "nothing was examined".',
  });
  examinedSkills = 0;
  const frozen = new Set(baseline ?? readBaseline());
  const findings = [];
  const at = (skill, detail) => findings.push({ skill, detail });
  const present = new Set();

  for (const name of readdirSync(path.join(root, SKILLS_DIR)).sort()) {
    const file = path.join(root, SKILLS_DIR, name, 'SKILL.md');
    if (!existsSync(file)) continue;
    const text = readFileSync(file, 'utf8');
    const declaration = parseDeclaration(text);
    // `over=delegated` REFERS to a loop it does not drive, so it has no run of its own to prove.
    if (declaration === undefined || declaration.over === 'delegated') continue;
    examinedSkills += 1;
    present.add(name);

    let closedRuns;
    try {
      closedRuns = readLedger(root, name).filter(
        (entry) => entry.terminal !== null && entry.terminal !== undefined,
      );
    } catch (error) {
      // An unreadable ledger is not "no runs yet": those two are exactly what this floor separates.
      at(name, error.message);
      continue;
    }

    const exemption = String(frontmatterObject(text)?.proof ?? '');
    const exempted = EXEMPTION.test(exemption.trim());

    if (frozen.has(name)) {
      // Anti-rot, the shrink-only direction: an exemption may not outlive the need for it.
      if (closedRuns.length > 0) {
        at(
          name,
          'is frozen in the baseline and now has a closed loop run — remove it from ' +
            `${path.relative(WORKSPACE_ROOT, BASELINE_FILE)} in the SAME change, or the set rots around it`,
        );
      }
      continue;
    }

    if (closedRuns.length > 0 || exempted) continue;

    if (exemption !== '' && !exempted) {
      at(
        name,
        `declares \`proof: ${exemption}\` with no reason after the dash. An exception nobody had to justify is the one that spreads — write \`proof: none — <why a real run is not obtainable>\``,
      );
      continue;
    }

    at(
      name,
      'drives a loop and has never been proven: no closed entry in its `.agents/loop-runs/` ledger, no ' +
        '`proof: none — <reason>`, and no baseline entry. Drive it once through `loop-run.mjs` and close ' +
        'the run, or declare why a real run is not obtainable',
    );
  }

  for (const name of frozen) {
    if (!present.has(name)) {
      at(
        name,
        `is frozen in ${path.relative(WORKSPACE_ROOT, BASELINE_FILE)} but drives no loop any more — prune it`,
      );
    }
  }
  return findings;
}

function main() {
  const findings = findLoopProofFindings();
  console.error(`::examined:: ${examinedSkillCount()} loop-driving skills`);
  if (findings.length === 0) {
    console.log(
      `loop-proof scan passed (${examinedSkillCount()} loop-driving skill(s) examined; ` +
        `${readBaseline().length} frozen at adoption). It establishes that a terminal signal was reached ` +
        "once — not that the run exercised the loop's hard path.",
    );
    return 0;
  }
  console.error('loop-proof scan failed:');
  for (const f of findings) console.error(`  - ${f.skill}: ${f.detail}`);
  return 1;
}

const isDirectExecution =
  process.argv[1] !== undefined && process.argv[1].endsWith('scan-loop-proof.mjs');
if (isDirectExecution) process.exitCode = main();
