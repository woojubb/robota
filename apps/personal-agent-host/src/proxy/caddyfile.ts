import { createHash } from 'node:crypto';

import { HostError } from '../errors.js';
import type { ProxySite } from './port.js';
import {
  validateEmail,
  validateHostname,
  validatePort,
  validateSocketPath,
  validateUpstream,
} from './validate.js';

export type ProxyTls = { mode: 'internal' } | { mode: 'acme'; email: string };

export interface ICaddyfileSettings {
  tls: ProxyTls;
  /** Where the proxy listens for its admin API; always a Unix socket, never a TCP address. */
  adminListen: string;
  httpPort?: number;
  httpsPort?: number;
  /** How long a live stream (a WebSocket) outlives a reload. */
  streamCloseDelaySeconds?: number;
}

export const DEFAULT_STREAM_CLOSE_DELAY_SECONDS = 600;
const MAX_STREAM_CLOSE_DELAY_SECONDS = 86_400;

const UNAVAILABLE_BODY = {
  suspended: 'This account is suspended.',
  unavailable: 'This account is temporarily unavailable.',
} as const;

function route(upstream: string, delay: number): string[] {
  return [`\t\treverse_proxy ${upstream} {`, `\t\t\tstream_close_delay ${delay}s`, '\t\t}'];
}

function siteBlock(site: ProxySite, tls: ProxyTls, delay: number): string {
  const hostname = validateHostname(site.hostname);
  // Each listed hostname asks for its own certificate when the configuration loads; a name that is
  // not listed never reaches issuance, because nothing here can request a certificate on demand.
  const lines: string[] = [`${hostname} {`];
  if (tls.mode === 'internal') lines.push('\ttls internal');
  if (site.kind === 'active') {
    const gui = validateUpstream(site.guiUpstream);
    const ws = validateUpstream(site.wsUpstream);
    lines.push('\tencode zstd gzip', '\theader -Server');
    lines.push('\thandle_path /ws/* {', ...route(ws, delay), '\t}');
    lines.push('\thandle {', ...route(gui, delay), '\t}');
  } else if (site.kind === 'suspended' || site.kind === 'unavailable') {
    lines.push('\theader -Server', `\trespond "${UNAVAILABLE_BODY[site.kind]}" 503`);
  } else {
    throw new HostError('invalid-input', 'Proxy configuration refused: unknown site kind');
  }
  lines.push('}');
  return lines.join('\n');
}

/**
 * Renders the proxy configuration for exactly the given sites. Only listed hostnames appear, so
 * only they get a certificate; there is no catch-all site, no on-demand issuance and no default
 * certificate. The output depends on the sites alone, in hostname order.
 */
export function generateCaddyfile(
  sites: readonly ProxySite[],
  settings: ICaddyfileSettings,
): string {
  const adminListen = validateSocketPath(settings.adminListen, 'admin socket');
  const delay = settings.streamCloseDelaySeconds ?? DEFAULT_STREAM_CLOSE_DELAY_SECONDS;
  if (!Number.isInteger(delay) || delay < 0 || delay > MAX_STREAM_CLOSE_DELAY_SECONDS) {
    throw new HostError('invalid-input', 'Proxy configuration refused: stream close delay');
  }
  const email = settings.tls.mode === 'acme' ? validateEmail(settings.tls.email) : undefined;

  const seen = new Set<string>();
  for (const site of sites) {
    const hostname = validateHostname(site.hostname);
    if (seen.has(hostname)) {
      throw new HostError(
        'invalid-input',
        `Proxy configuration refused: hostname ${hostname} is listed twice`,
      );
    }
    seen.add(hostname);
  }
  const ordered = [...sites].sort((a, b) => (a.hostname < b.hostname ? -1 : 1));

  // The admin API is a Unix socket only, readable and writable by its owner.
  const global: string[] = ['{', `\tadmin unix/${adminListen}|0600`, '\tskip_install_trust'];
  if (email !== undefined) global.push(`\temail ${email}`);
  if (settings.httpPort !== undefined) {
    global.push(`\thttp_port ${validatePort(settings.httpPort, 'HTTP port')}`);
  }
  if (settings.httpsPort !== undefined) {
    global.push(`\thttps_port ${validatePort(settings.httpsPort, 'HTTPS port')}`);
  }
  global.push('\tservers {', '\t\tstrict_sni_host', '\t}', '}');

  const header = '# Generated by personal-agent-host; the control plane rewrites this file.';
  const blocks = ordered.map((site) => siteBlock(site, settings.tls, delay));
  return `${[header, global.join('\n'), ...blocks].join('\n\n')}\n`;
}

/** Identifies a configuration for comparison in status output. */
export function configHash(text: string): string {
  return createHash('sha256').update(text).digest('hex').slice(0, 16);
}
